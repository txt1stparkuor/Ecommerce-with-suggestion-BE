package com.txt1stparkuor.Ecommerce.domain.dto.response;

import io.swagger.v3.oas.annotations.media.Schema;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.math.BigDecimal;
import java.math.RoundingMode;

@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
@Schema(description = "Top selling product item for analytics dashboard")
public class TopProductResponse {

    @Schema(description = "Product unique identifier", example = "prod-abc-123")
    private String productId;

    @Schema(description = "Product name", example = "Wireless Noise-Cancelling Headphones")
    private String productName;

    @Schema(description = "Total number of units sold across non-cancelled orders", example = "120")
    private long unitsSold;

    @Schema(description = "Total revenue generated by this product across non-cancelled orders", example = "11999.00")
    private BigDecimal totalRevenue;

    /**
     * JPQL constructor expression constructor.
     * Maps database aggregations (SUM(Integer) -> Long, SUM(Double * Integer) -> Double)
     * and normalizes total revenue into a 2-decimal scale BigDecimal.
     */
    public TopProductResponse(String productId, String productName, Long unitsSold, Double totalRevenue) {
        this.productId = productId;
        this.productName = productName;
        this.unitsSold = unitsSold != null ? unitsSold : 0L;
        this.totalRevenue = totalRevenue != null
                ? BigDecimal.valueOf(totalRevenue).setScale(2, RoundingMode.HALF_UP)
                : BigDecimal.ZERO.setScale(2, RoundingMode.HALF_UP);
    }
}
